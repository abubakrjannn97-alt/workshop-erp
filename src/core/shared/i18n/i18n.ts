const ALL: Record<Locale, Dict> = { ru, tj };

export function translate(locale: Locale, key: string) {
  const overrides = getDomainI18nOverrides(locale);
  return overrides[key] ?? ALL[locale][key] ?? ALL.ru[key] ?? key;
}

export function createT(locale: Locale) {
  return (key: string, vars?: Record<string, string | number>) => {
    let s = translate(locale, key);
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replaceAll("{" + k + "}", String(v));
      }
    }
    return s;
  };
}

/** Translate seeded DB codes (status/fund/role/…); fall back to stored name. */
export function named(locale: Locale, prefix: string, code: string, fallback?: string) {
  const key = `${prefix}.${code}`;
  return ALL[locale][key] ?? ALL.ru[key] ?? fallback ?? code;
}

export function intlLocale(locale: Locale) {
  return locale === "tj" ? "tg-TJ" : "ru-RU";
}

/** Client-safe locale from cookie (error boundaries / client widgets). */
export function getClientLocale(): Locale {
  if (typeof document === "undefined") return DEFAULT_LOCALE;
  const m = document.cookie.match(/(?:^|; )workshop_locale=([^;]*)/);
  const raw = m?.[1] ? decodeURIComponent(m[1]) : "";
  if (raw && (LOCALES as string[]).includes(raw)) return raw as Locale;
  return DEFAULT_LOCALE;
}
